package com.gimy.tv.ui

/**
 * 會在多個畫面出現的共用文案。
 *
 * 這裡是 Kotlin 常數而不是 string resource：整個 App 只有繁體中文一種語系，
 * 而且大部分文案是在 ViewModel 裡組出來的（stringResource 只能在 Composable 裡用）。
 * 放在這裡的判準是「同一句話會在兩個以上的地方出現」——只出現一次的文案留在原地，
 * 搬過來只會讓閱讀時多跳一次。
 */
object UiText {

    /**
     * 載入時網路失敗的統一說法。
     *
     * 收斂前同一件事有四種寫法：strings.xml 的「網路連線失敗，請檢查網路設定」、
     * 首頁的「無法載入內容，請檢查網路連線」、詳情與播放器的「網路連線失敗，請檢查網路後重試」。
     * 使用者在不同畫面看到不同說法，會以為是不同的錯誤。
     */
    const val NETWORK_ERROR = "網路連線失敗，請檢查網路後重試"
}
